/**
 * 获取完整的人物军官档案（含生卒年、传记、四维技能与战历）
 */
export function getCharacterDossier(c, world){
  if(!c) return null;
  const id = c.id || '';
  const spec = CHARACTER_DOSSIERS[id] || {};

  // 4D 属性计算 (攻、防、筹、术/后勤)
  const skills = {
    attack: (spec.skills && spec.skills.attack) || (c.skills && c.skills.attack) || (c.traits && c.traits.some(t => t.stat === 'attack') ? 5 : 3),
    defense: (spec.skills && spec.skills.defense) || (c.skills && c.skills.defense) || (c.traits && c.traits.some(t => t.stat === 'defense') ? 5 : 3),
    planning: (spec.skills && spec.skills.planning) || (c.skills && c.skills.planning) || (c.traits && c.traits.some(t => t.stat === 'plan_speed') ? 5 : 4),
    logistics: (spec.skills && spec.skills.logistics) || (c.skills && c.skills.logistics) || 3
  };

  // 生卒年与原籍
  const lifespan = spec.lifespan || (c.era === 'ww1' ? '1870年 - 1935年 (一战军官)' : c.era === 'ww2' ? '1895年 - 1960年 (二战高级将领)' : '当代历史人物');
  const origin = spec.origin || (c.type === 'leader' ? `${c.nat} 最高国家首脑` : `${c.nat} 国防军战区高级将领`);

  // 详尽历史评传 (若未显式指定，生成具备高度学术考据质感的详尽评述)
  let bio = spec.bio || c.bio;
  if(!bio || bio.length < 50){
    if(c.type === 'leader'){
      bio = `${c.name}，${c.nat}国家元首与最高战略决断者。在${c.era === 'ww1' ? '一战大国博弈' : c.era === 'ww2' ? '第二次世界大战全面风暴' : c.era === 'coldwar' ? '美苏铁幕对峙' : '现代多极博弈'}的重大历史转折关口，肩负国家生死存亡与阵营结盟重任。其执政路线深度整合了战时工业动员、全民凝聚力与统帅部指挥权威，深刻影响了世界地缘格局演进。`;
    } else {
      bio = `${c.name}，${c.nat}陆军战区骨干指挥官。长年征战于前线关键要塞与突击主轴，精通大军团多兵种联合阵地攻防法。曾多次在危难时刻指挥所辖师团构筑坚固防线或执行大纵深穿插包抄，在军中享有极高战术声誉与统帅威信。`;
    }
  }

  // 特性列表
  const traits = (spec.traitsDesc && spec.traitsDesc.length) ? spec.traitsDesc : (c.traits || []).map(t => ({
    name: t.stat === 'attack' ? '突击猛攻' : t.stat === 'defense' ? '坚壁清野' : t.stat === 'speed' ? '快速穿插' : '战略筹划',
    desc: `${t.stat}: +${Math.round(t.value * 100)}% 核心战斗修正`
  }));

  // 所辖部队统计 (根据 world 中的 assignedGenerals 或 units)
  let assignedCount = 0;
  if(world && world.units){
    const playerNat = c.nat || (world.nations[world.player] ? world.player : '');
    const myUnits = world.units.filter(u => u.nat === playerNat && u.hp > 0);
    assignedCount = Math.round(myUnits.length / Math.max(1, (world.nations[playerNat]?.assignedGenerals?.length || 1)));
  }

  return {
    id,
    name: c.name || id,
    nat: c.nat || 'GER',
    type: c.type || 'general',
    rank: c.rank || (c.type === 'leader' ? 'leader' : 'general'),
    portrait: c.portrait,
    lifespan,
    origin,
    bio,
    skills,
    traits,
    assignedCount,
    isFictional: !!c.fictional
  };
}

/**
 * 获取完整的国策战略档案（含母图、150字历史背景、互斥与前置分析、数值收益）
 */
export function getFocusDossier(f, world){
  if(!f) return null;
  const id = f.id || '';
  const spec = FOCUS_HISTORICAL_DOSSIERS[id] || {};

  const chain = f.chain || spec.category || 'industry';
  const motherIcon = getFocusMotherIconSrc(chain);
  const blueprint = (chain === 'armor' || id.includes('armor') || id.includes('tank'))
    ? getBlueprintSrc('tank')
    : (chain === 'army' || id.includes('inf'))
    ? getBlueprintSrc('inf_equip')
    : null;

  const title = f.name || spec.title || id;
  const quote = spec.quote || '';

  // 150+ 字深度历史考据
  let history = spec.history;
  if(!history || history.length < 50){
    history = `【${title}】是 ${f.chain === 'industry' ? '国家工业总体动员体系' : f.chain === 'army' ? '陆军核心战术与统帅学说' : f.chain === 'air' ? '空中战役制空权建设' : f.chain === 'navy' ? '大洋控制与通商破交战' : '国家战略地缘扩张与外交同盟'}的关键抉择。在当时错综复杂的国际地缘风云变幻中，该国策的启动意味着统帅部决定集中全民族宝贵资源打破僵局，不仅直接改写了前线部队的战备水准，更对周边势力的安全神经带来了深远的战略震荡。`;
  }

  // 前置与互斥
  const reqs = f.requires || f.pre || [];
  const exclusive = spec.exclusiveWith || f.exclusiveWith || null;

  // 效果格式化
  const effects = (f.effects || []).map(e => {
    if(e.type === 'addFactory') return `新增 ${e.count || e.value} 座${e.kind === 'mil' ? '军用工厂' : '民用工厂'}`;
    if(e.type === 'addEquip') return `增加装备储备 +${e.value}`;
    if(e.type === 'addPP') return `获得政治点 +${e.value} PP`;
    if(e.type === 'addArmyXp') return `获得陆军实战经验 +${e.value} XP`;
    if(e.type === 'addStability') return `国家稳定度 +${e.value}%`;
    if(e.type === 'addWarSupport') return `国家战争支持度 +${e.value}%`;
    if(e.type === 'declareWar') return `对目标国家【${e.target}】全面宣战`;
    if(e.type === 'unlockTech') return `立即解锁关键军事科技【${e.tech}】`;
    if(e.type === 'modifier') return `${e.stat} 修正 +${Math.round((e.value || 0)*100)}%`;
    return JSON.stringify(e);
  });

  return {
    id,
    chain,
    title,
    quote,
    motherIcon,
    blueprint,
    days: f.days || 70,
    ppCost: 1.0,
    history,
    effects,
    reqs,
    exclusive
  };
}
