// 方位与地形前缀修饰词，保证大图地名绝不突兀重复
const PREFIXES = ['东', '西', '南', '北', '上', '下', '外', '新', '大', '前'];

/** 获取确定性历史行省地名 (v10.0 §2 M2) */
export function getProvinceHistoricalName(world, hex, eraKey = 'ww2') {
  if (!hex) return '';
  if (hex.city && hex.city.name) return hex.city.name;

  const era = eraKey || (world && world.era) || 'ww2';
  const pool = PROVINCE_NAMES_BY_ERA[era] || PROVINCE_NAMES_BY_ERA.ww2;
  const hash = Math.abs(Math.imul(hex.q * 73856093 ^ hex.r * 19349663, 83492791)) >>> 0;

  const baseIdx = hash % pool.length;
  const baseName = pool[baseIdx];

  // 若存在多余重复，用确定性方位修饰词去重
  const prefixIdx = Math.floor(hash / pool.length) % (PREFIXES.length * 3);
  if (prefixIdx < PREFIXES.length) {
    return PREFIXES[prefixIdx] + baseName;
  }
  return baseName;
}

/** 为全地图所有 hex 补齐并赋予真实历史行省名称 (C39 拓扑无损) */
export function assignHistoricalProvinceNames(world) {
  if (!world || !world.hexes) return;
  const eraKey = world.era || (world.scenario === 'ww1' ? 'ww1' : world.scenario === 'coldwar' ? 'coldwar' : world.scenario === 'modern' ? 'modern' : 'ww2');

  const usedNames = new Set();
  for (const h of world.hexes) {
    if (h.terrain === 'sea') {
      h.name = '';
      continue;
    }
    if (h.city && h.city.name) {
      h.name = h.city.name;
      usedNames.add(h.name);
      continue;
    }
    let name = getProvinceHistoricalName(world, h, eraKey);
    let guard = 0;
    while (usedNames.has(name) && guard < 10) {
      const pfx = PREFIXES[(guard + (h.q & 3)) % PREFIXES.length];
      name = pfx + name.replace(/^[东西南北上下外新大前]/, '');
      guard++;
    }
    usedNames.add(name);
    h.name = name;
    if (h.cell) h.cell.name = name;
  }
}
